import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const service = readFileSync('lib/agents/runtime/native-supervisor-service.ts', 'utf8')
const runtime = readFileSync('lib/agents/runtime/native-autonomy-runtime.ts', 'utf8')
const specialist = readFileSync('lib/agents/governance-specialist-agent.ts', 'utf8')
const route = readFileSync('app/api/agents/supervisor/run/route.ts', 'utf8')
const migration = readFileSync('supabase/migrations/20260912033500_native_supervisor_production_entrypoint.sql', 'utf8')

function contains(source, token, label) {
  assert.ok(source.includes(token), `${label} is missing: ${token}`)
}

contains(migration, "'native_supervisor_agent'", 'supervisor controller definition')
contains(migration, "'controller_only', true", 'controller-only configuration')
contains(migration, 'if v_tool_count <> 0 then', 'no supervisor-owned tools postcondition')
contains(route, "authorizeProject(user.id, projectId, 'agent.execute')", 'project authorization')
contains(route, 'runNativeSpecialistSupervisor({', 'production supervisor service call')
contains(route, 'workers.length < 1 || workers.length > 6', 'bounded worker count')
contains(service, "status: 'RUNNING'", 'supervisor run creation')
contains(service, 'parent_run_id: supervisorRun.id', 'child run parent linkage')
contains(service, "status: 'QUEUED'", 'child pre-creation before execution')
contains(service, 'startNativeAgentLifecycle({', 'supervisor runtime pinning')
contains(service, "phase: 'PLANNING'", 'supervisor planning checkpoint')
contains(service, 'bindNativePlanToPinnedRuntime({', 'deterministic pinned plan binding')
contains(service, 'executeNativeBoundRuntimePlan({', 'closed-loop production execution')
contains(service, 'initialCheckpointId: lifecycle.checkpointId', 'checkpoint lineage continuity')
contains(service, 'allowTier2AutomaticExecution: false', 'read-only first-slice policy')
contains(service, "toolKey: 'governance_specialist_investigate'", 'specialist native tool plan')
contains(service, 'existingAgentRunId: binding.agentRunId', 'pre-created child run execution')
contains(service, 'nativeAttempt: attempt', 'bounded retry attempt identity')
contains(service, 'NATIVE_SUPERVISOR_ABORTED', 'orphan child fail-closed cleanup')
contains(service, 'goal_hash: goalHash', 'hash-only supervisor goal persistence')
assert.equal(service.includes('input: { goal,'), false, 'raw supervisor goal must not be persisted in agent run input')
contains(runtime, 'initialCheckpointId?: string | null', 'runtime initial checkpoint binding')
contains(runtime, 'input.initialCheckpointId ?? null', 'runtime checkpoint chain initialization')
contains(specialist, 'existingAgentRunId?: string | null', 'specialist supervisor-bound run support')
contains(specialist, 'nativeAttempt?: number', 'specialist retry attempt support')
contains(specialist, "['QUEUED', 'FAILED', 'RUNNING']", 'supervisor-bound retry statuses')
contains(specialist, 'native_supervisor_specialist_read_only', 'supervisor execution mode')
contains(specialist, 'attempt:${Math.max(1, input.nativeAttempt ?? 1)}', 'per-attempt native idempotency key')
const bindIndex = service.indexOf('bindNativePlanToPinnedRuntime({')
const executeIndex = service.indexOf('executeNativeBoundRuntimePlan({')
assert.ok(bindIndex >= 0 && executeIndex > bindIndex, 'plan must be bound and validated before execution')
const lifecycleIndex = service.indexOf('startNativeAgentLifecycle({')
const childIndex = service.indexOf('parent_run_id: supervisorRun.id')
assert.ok(lifecycleIndex >= 0 && childIndex > lifecycleIndex, 'supervisor manifest must be pinned before child runs are created')
console.log('Native supervisor production entrypoint verified.')
