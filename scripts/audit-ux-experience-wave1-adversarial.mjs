import assert from 'node:assert/strict'
import fs from 'node:fs'

const search=fs.readFileSync('app/search/global-search.tsx','utf8')
const journey=fs.readFileSync('app/journeys/page.tsx','utf8')
const copilot=fs.readFileSync('app/api/ai/copilot/chat/route.ts','utf8')
const trust=fs.readFileSync('components/governance/dataset-trust-signals.tsx','utf8')
const notFound=fs.readFileSync('app/not-found.tsx','utf8')
const telemetry=fs.readFileSync('app/api/ux/interaction/route.ts','utf8')
const telemetryClient=fs.readFileSync('components/app-shell/ux-interaction-telemetry.ts','utf8')

assert.ok(search.includes('DataNexus will not fabricate a match.'),'zero-result search must reject fabricated discovery')
assert.ok(!/setResults\(\[\{/.test(search),'search UI must not manufacture fallback results')
assert.ok(journey.includes('steps.find(step => !step.complete)'),'next best action must derive from unsatisfied deterministic evidence')
assert.ok(!/generate|llm|copilot/i.test(journey.slice(journey.indexOf('const nextStep'),journey.indexOf('const completed'))),'next best action selection must not depend on AI generation')
assert.ok(copilot.includes('Never invent counts, classifications, certifications, incidents, controls, regulatory conclusions, or business impact.'),'copilot must explicitly reject invented governance claims')
assert.ok(copilot.includes('Do not claim governance approval, remediation completion, certification, compliance, or authority unless the supplied evidence proves it.'),'copilot must preserve authority boundaries')
assert.ok(trust.includes('Persisted governance and profiling evidence only.'),'trust signals must declare persisted evidence authority')
assert.ok(trust.includes('No AI-generated trust state'),'trust state must not be generated by AI')
assert.ok(notFound.includes('The resource may have moved, been removed, or no longer be available'),'404 must explain recoverable causes without inventing deletion')
assert.ok(notFound.includes('No data was changed.'),'404 must not imply a mutation occurred')
assert.ok(telemetry.includes('const EVENT_TYPES=new Set(['),'telemetry events must be allow-listed')
assert.ok(telemetry.includes('const SURFACES=new Set(['),'telemetry surfaces must be allow-listed')
assert.ok(!/payload:\s*body/.test(telemetry),'telemetry must not persist arbitrary request bodies')
assert.ok(!/\.\.\.body/.test(telemetry),'telemetry must not spread arbitrary request payload into persistence')
assert.ok(telemetry.includes("authorizeProject(user.id,projectId,'catalog.read')"),'telemetry must fail closed on project authorization')
assert.ok(telemetryClient.includes('must never block governed work'),'telemetry client failure must remain non-blocking')
console.log('Independent adversarial audit passed for DataNexus UX Experience Wave 1.')
