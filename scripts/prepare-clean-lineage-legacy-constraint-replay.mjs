import fs from 'node:fs'
import path from 'node:path'

const targetDir = process.env.TARGET_MIGRATION_DIR
if (!targetDir) throw new Error('TARGET_MIGRATION_DIR is required')
if (!fs.existsSync(targetDir)) throw new Error(`TARGET_MIGRATION_DIR does not exist: ${targetDir}`)

const version = '20260904165920'
const replay = `${version}_restore_legacy_lineage_edge_constraint.sql`
const targetPath = path.join(targetDir, replay)
const collision = fs.readdirSync(targetDir).some((name) => name.startsWith(`${version}_`))
if (collision) throw new Error(`Legacy lineage constraint replay version collides with existing migration ${version}`)

const sql = `
alter table governance.lineage_edges
  add constraint lineage_edges_source_type_source_id_target_type_target_id_r_key
  unique (source_type, source_id, target_type, target_id, relationship);
`

fs.writeFileSync(targetPath, sql.trimStart())
console.log(`RECONSTRUCTED ${replay}: released tenant hardening drops the historical lineage-edge uniqueness constraint by its autogenerated name; replay restores that exact legacy constraint before hardening.`)
